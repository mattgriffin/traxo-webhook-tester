// Default segment types by classification
const classificationSegments = {
  airline: ['flight'],
  hotel: ['hotel'],
  car: ['car'],
  rail: ['rail'],
  transportation: ['activity'],
  tmc: ['flight', 'hotel', 'car', 'rail', 'activity'],
  ota: ['flight', 'hotel', 'car'],
};

// Get allowed segment types for a source
export function getAllowedSegments(source) {
  return source.segments || classificationSegments[source.classification] || [];
}

// Get sources filtered to those that can generate segments
export function getUsableSources() {
  return sources.filter(s => getAllowedSegments(s).length > 0);
}

// Get sources by classification
export function getSourcesByClassification(classification) {
  return sources.filter(s => s.classification === classification);
}
